import struct
import sys

def find_fv(data):
    off = 0
    while off + 0x48 <= len(data):
        if struct.unpack_from("<I", data, off + 0x28)[0] == 0x4856465F:
            return off
        off += 8
    return None

def find_fv_containing(data, off):
    start = 0
    while start + 0x48 <= len(data):
        if struct.unpack_from("<I", data, start + 0x28)[0] == 0x4856465F:
            fvlen = struct.unpack_from("<Q", data, start + 0x20)[0]
            if start <= off < start + fvlen:
                return start
            start += (fvlen + 7) & ~7
        else:
            start += 8
    return 0

def find_sec_image(data):
    n = len(data)
    for i in range(0x40, n - 0x400):
        if data[i + 3] != 0x10:
            continue
        size = data[i] | (data[i + 1] << 8) | (data[i + 2] << 16)
        if size < 0x400 or size > 0x200000:
            continue
        b = i + 4
        if data[b:b + 2] != b"MZ":
            continue
        e = struct.unpack_from("<I", data, b + 0x3C)[0]
        if e > 0x400 or b + e + 0x100 > n:
            continue
        if data[b + e:b + e + 4] != b"PE\x00\x00":
            continue
        mach = struct.unpack_from("<H", data, b + e + 4)[0]
        nsec = struct.unpack_from("<H", data, b + e + 6)[0]
        optsz = struct.unpack_from("<H", data, b + e + 20)[0]
        magic = struct.unpack_from("<H", data, b + e + 24)[0]
        if not (mach in (0x8664, 0x14C) and magic in (0x20B, 0x10B) and nsec and optsz >= 0xE0):
            continue
        return b, size
    return None, None

def pe_info(pe):
    e = struct.unpack_from("<I", pe, 0x3C)[0]
    optsz = struct.unpack_from("<H", pe, e + 20)[0]
    entry = struct.unpack_from("<I", pe, e + 0x28)[0]
    magic = struct.unpack_from("<H", pe, e + 24)[0]
    base = struct.unpack_from("<Q" if magic == 0x20B else "<I", pe, e + (0x30 if magic == 0x20B else 0x34))[0]
    reloc_rva = struct.unpack_from("<I", pe, e + 0x18 + 0x70 + 5 * 8)[0]
    reloc_size = struct.unpack_from("<I", pe, e + 0x18 + 0x70 + 5 * 8 + 4)[0]
    return entry, base, reloc_rva, reloc_size

def main():
    data = open(sys.argv[1], "rb").read()
    fv = find_fv(data)
    pe_off, pe_size = find_sec_image(data)
    if pe_off is None:
        raise SystemExit("no sec module found")
    pe = data[pe_off:pe_off + pe_size]
    entry, base, reloc_rva, reloc_size = pe_info(pe)
    sec_fv_off = find_fv_containing(data, pe_off)
    flash_base = base - pe_off
    print("firmware volume      : 0x%06x" % (fv or 0))
    print("SEC FV file offset   : 0x%06x" % sec_fv_off)
    print("SEC module file off  : 0x%06x" % pe_off)
    print("SEC entry RVA        : 0x%05x" % entry)
    print("SEC link base        : 0x%016x" % base)
    print("flash base           : 0x%016x" % flash_base)
    print("reloc dir rva/size   : 0x%05x / 0x%x" % (reloc_rva, reloc_size))
    print("image size           : 0x%x" % len(data))
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/gen_ovmf64.py - do not edit manually. */\n")
        f.write("#ifndef OVMF64_CONSTANTS_H\n#define OVMF64_CONSTANTS_H\n\n")
        f.write("#define OVMF64_FLASH_BASE        0x%016XULL\n" % flash_base)
        f.write("#define OVMF64_IMAGE_SIZE        0x%08XU\n" % len(data))
        f.write("#define OVMF64_SEC_FV_OFFSET     0x%08XU\n" % sec_fv_off)
        f.write("#define OVMF64_SEC_FILE_OFFSET   0x%08XU\n" % pe_off)
        f.write("#define OVMF64_SEC_ENTRY_RVA     0x%08XU\n" % entry)
        f.write("#define OVMF64_SEC_LINK_BASE     0x%016XULL\n" % base)
        f.write("#define OVMF64_SEC_RELOC_RVA     0x%08XU\n" % reloc_rva)
        f.write("#define OVMF64_SEC_RELOC_SIZE    0x%08XU\n" % reloc_size)
        f.write("#define OVMF64_TEMP_RAM_STACK    0x%08XU\n" % 0x820000)
        f.write("\n#endif\n")

if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_ovmf64.py OVMF_CODE.fd out.h")
    main()
